/**
 * 「一条任务都还没有」时该说的那句话。
 *
 * 空状态在这个应用里有个统一的标准：**说清楚怎么让它有内容**（纪念日那句
 * 「上面填一个日期就行——考试、生日……」、回顾那句「让 AI 跑一遍分析」都是
 * 这么写的）。唯独「一条都还没有」这种全新状态没被单独对待——「今天」说
 * 「今天没有要做的」，「按来源」说「空的」。
 *
 * 那两句在有任务的时候是对的，**在一台刚装好的机器上是误导**：它们把「你今天
 * 很闲」和「这个应用还是空的、而你不知道从哪儿开始」说成同一句话。第一次
 * 打开这个应用的人，需要的恰恰是后面那半句。
 *
 * 写成常量而不是各写一句：两处说的是同一件事，各写一份迟早一处改了另一处
 * 还是老话——这个仓库为「同一个概念两处文案」栽过好几次。
 *
 * ## 最后那半句为什么是「按 ?」
 *
 * 这个应用有六十多个键盘快捷键（`keymap.ts`），而它们在界面上**一个字都没写**：
 * `?` 打开快捷键一览，`Ctrl+K` 打开命令面板，两条路都得先知道才按得出来。
 * 一个人站在空的「今天」面前，恰恰是最需要这些的时刻——他已经卡住了，而出口
 * 藏在两个他不可能猜到的键上。
 *
 * **为什么写进空状态而不是别的地方**：这条话只在「一台刚装好、还没有任何任务」
 * 时说一次，正好是那个「不知道从哪儿下手」的时刻；常驻提示会在他建完第一条之后
 * 继续占地方，而那时候他已经不需要了。
 *
 * **`?` 要套上「」。**
 *
 * 这句原本是 `按 ? ，那里列着…`，先后改过两次，两次都是真问题：
 *
 * 1. **全角逗号前面多一个空格**——`按 ? ，那里`。全角标点自带左右留白，前面再
 *    加一个等于叠了两份。
 * 2. **去掉空格之后仍然是 `按 ?，那里`**——比第一版更难读。半角 `?` 紧挨一个全角
 *    逗号，读者会把它当成**问号**：「不知道从哪儿下手？，那里列着…」。而它本意是
 *    「按这个键」。句意整个拧了。
 *
 * 快捷键表（`ShortcutHelp.tsx`）里 `?` 是裸写在一列里的，有表头兜着不会歧义；
 * **正文里没有表头**，半角符号就归位成标点了。
 *
 * 修法是套「」而不是加个「键」字：**同一句话里已经有两处这么点名屏幕上的东西**
 * （「添加任务」「随手记」），`?` 是第三个，不该是唯一一个不套的。
 *
 * 跟 `lib/cjkWrap.guard.test.ts` 是同一族但不同判据（那条查 JSX 折行折出来的
 * 空格），守卫在 `lib/cjkPunct.guard.test.ts`，那里两条判据都有。
 */
export const FIRST_RUN_HINT =
  '还没有任何任务。上面那行「添加任务」直接写一条；想不清楚就先写进「随手记」——'
  + '接了 AI 它会拆成任务，没接也能在收件箱里手动拆。不知道从哪儿下手就按「?」，那里列着所有快捷键。';

/** 整个应用是不是还空着。`tasks` 是全表，不是当前视图筛出来的那一份——
 *  判据是「有没有任务这回事」，不是「这个去处有没有」。 */
export const isFirstRun = (tasks: unknown[]): boolean => tasks.length === 0;

/**
 * 「还没读到过」的那两句，跟上面那句同一个族：**都在断言「有没有」**，
 * 而 `tasks` 的初值 `[]` 在「真没有」「还在飞」「已经失败」三种情况之间
 * 分不出来。打磨稿拿离线夹具量「今天」那一屏时现形——本地快照里有 18 条，
 * 屏幕上那句是「还没有任何任务」。
 *
 * 三档分开说，因为「正在读」和「读不到」给出的下一步不一样（一个是等，
 * 一个是去起服务 / 填地址），而两种都不该是「你去建一条」。
 */
export const READING_HINT = '正在读任务列表…';
export const NOT_READ_HINT = '没能读到任务列表——不是没有，是还没读到。';

/**
 * 读到过 ⇒ `null`（调用方照旧按自己的空态说），没读到 ⇒ 该顶上那一句。
 *
 * 判据来自调用方那两个记号（`App.tsx` 的 `tasksLoaded` / `tasksFailed`），
 * 不在这里自己猜：这一层只负责「还没读到的时候说哪句」，不负责知道读到没读到。
 */
export const readHint = (loaded: boolean, failed: boolean): string | null =>
  (loaded ? null : failed ? NOT_READ_HINT : READING_HINT);
