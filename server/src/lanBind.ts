/**
 * LAN=1 时把服务绑到 0.0.0.0（同一个 Wi-Fi 下任何设备都能连上），不设就还是
 * 127.0.0.1（只有这台机器自己能连）——这是这个项目第一次把 `data/` 暴露到
 * 本机之外，默认必须不变，开局域网必须是显式的一步。
 *
 * 只认字面量 `'1'`：`'true'`/`'yes'` 这类宽松写法不算，免得手滑设成别的
 * 值也意外打开了局域网。
 */
export function resolveBindHost(env: NodeJS.ProcessEnv): '0.0.0.0' | '127.0.0.1' {
  return env.LAN === '1' ? '0.0.0.0' : '127.0.0.1';
}

/**
 * 绑上 0.0.0.0 之后要在控制台印的醒目提示：同一个 Wi-Fi 下任何设备都能读写
 * 全部任务，没有任何认证，别在公共 Wi-Fi 上开。这一批不做认证（个人自用、
 * 家庭 Wi-Fi），这句提示是唯一的防线。
 *
 * **两条后果原来没写进这句提示，实测发现之后补的**（final-review.md I1/I2）：
 * - `POST /api/expand`、`POST /api/review` 局域网内无认证可达，能触发一次真实的 `claude -p`
 *   子进程——不只是「读写任务」，是「花掉你的订阅额度」。而且它是简单请求
 *   （`POST` 不带/带简单 `Content-Type`），不触发预检，CORS 白名单挡不住，
 *   任意网页的 `fetch(..., {mode:'no-cors'})` 都能打进来。
 * - `webhookUrl` 改掉之后，**关掉 `LAN=1`、重启服务都不会自己恢复**——它是
 *   settings 里持久化的一个字段，此后每条提醒都会把任务原文 POST 给那个地址，
 *   是唯一一条能活过「关闭局域网模式」这个动作本身的外泄通道。
 * 这两条不写清楚，用户是拿着一句不完整的话在决定要不要开 `LAN=1`。
 */
export const LAN_WARNING =
  '⚠️ 局域网模式已开启（LAN=1），服务绑在 0.0.0.0：同一个 Wi-Fi 下的任何设备都能' +
  '读写你的全部任务（收件箱原文、任务内容，没有任何认证），还能触发 AI 拆解和回顾（花你的' +
  '订阅额度）、改掉提醒 webhook（这一条改了之后，就算关掉局域网模式也不会自己恢复，' +
  '此后每条提醒都会把任务原文发给对方）、把 AI 接口地址改到别处（同样不会自己恢复；改了之后每次拆解都会把你的收件箱原文和全部任务发给那个地址）。别在咖啡馆、机场这类公共 Wi-Fi 上开这个模式。';

/**
 * 只有真的绑了 0.0.0.0 才打印 `LAN_WARNING`。`log` 可注入是为了能在测试里断言
 * 「到底有没有打印、打印的是不是这句话」——`index.ts` 起真实端口监听，没法在
 * vitest 里断言「绑的是哪个 host」（这个模块历来没有测试文件），这个函数把
 * 「要不要提示」这部分判断逻辑单独抽出来，让它至少这一半是能测的。
 */
export function logLanWarningIfNeeded(hostname: string, log: (msg: string) => void = console.log): void {
  if (hostname === '0.0.0.0') log(LAN_WARNING);
}
