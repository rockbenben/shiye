/**
 * 「一条任务都还没有」时该说的那句话。
 *
 * 空状态在这个应用里有个统一的标准：**说清楚怎么让它有内容**（纪念日那句
 * 「上面填一个日期就行——考试、生日……」、回顾那句「让 AI 跑一遍分析」都是
 * 这么写的）。唯独「一条都还没有」这种全新状态没被单独对待——「今天」说
 * 「今天没有要做的」，「按来源」说「空的」。
 *
 * 那两句在有任务的时候是对的，**在一台刚装好的机器上是误导**：它们把「你今天
 * 很闲」和「这个应用还是空的、而你不知道从哪儿开始」说成同一句话。第一次
 * 打开这个应用的人，需要的恰恰是后面那半句。
 *
 * 写成常量而不是各写一句：两处说的是同一件事，各写一份迟早一处改了另一处
 * 还是老话——这个仓库为「同一个概念两处文案」栽过好几次。
 */
export const FIRST_RUN_HINT =
  '还没有任何任务。上面那行「添加任务」直接写一条；想不清楚就先写进「随手记」，AI 会替你拆成任务。';

/** 整个应用是不是还空着。`tasks` 是全表，不是当前视图筛出来的那一份——
 *  判据是「有没有任务这回事」，不是「这个去处有没有」。 */
export const isFirstRun = (tasks: unknown[]): boolean => tasks.length === 0;
