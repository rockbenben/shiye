import type { List, Task } from '../types.js';
import { inAllView } from './simpleViews.js';

/**
 * 归档一份清单之后该说一句什么。没什么可说的就返回 `null`。
 *
 * **补的是一处很扎眼的不对称**：删清单的确认框里写得清清楚楚——「里面那 12 条
 * 任务不会被删，只是不再属于任何清单」，而且顺手指了一句「只是不想再看见它的话，
 * 用『归档』更轻」；可**归档本身一声不吭**。于是那条推荐路径反而是两条里唯一
 * 不交代「里面那些任务会怎样」的那条。
 *
 * 而它们确实会怎样：**什么都不会发生**。归档只把这份清单从侧栏挪进「已归档」
 * 那一节、不再进「归到哪个清单」的候选（README 那句「这份不用了、别再往里放
 * 东西」），里面的任务照旧出现在「全部」「今天」「接下来」「日历」「搜索」里，
 * 也照旧算进那些地方的计数。归完一个做了一半的项目，那十几条没做完的任务会
 * 一直待在你每天看的那几屏上——不说一声的话，这是一个纯粹的意外。
 *
 * 数的是**还没了结的**（`inAllView`：done 和 abandoned 不算，搁置算），跟侧栏
 * 里那份清单后面挂着的数字是同一条判据——他刚刚看着那个数字点的归档，提示里
 * 报另一个数只会让人以为自己看错了。已完成的那些不报：归档多半正是「这个项目
 * 做完了」，把一堆做完的数出来是在制造一个不存在的问题。
 *
 * **智能清单不报**（`filter !== null`）：它是一份存下来的查询、不是容器，
 * 归档它一条任务都不牵动，`listId` 指着它的任务本来就不存在。
 *
 * 纯函数、不读时钟——`inAllView` 只看 `status`。
 */
export function archiveNote(list: List, tasks: Task[]): string | null {
  if (list.filter !== null) return null;
  const n = tasks.filter((t) => t.listId === list.id && inAllView(t)).length;
  if (n === 0) return null;
  return `已归档「${list.name}」。里面 ${n} 条没了结的任务照旧留在「全部」「今天」里——归档只是把这份清单收起来、不再往里放东西。`;
}
